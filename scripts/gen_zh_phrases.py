#!/usr/bin/env python3
import argparse
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
CHAR_INC = os.path.join(HERE, "..", "cpp", "hardcopy", "parser", "zh_convert_table.inc")


def load_chars():
    tables, cur = {}, None
    for line in open(CHAR_INC, encoding="utf-8"):
        m = re.match(r"static const ZhPair (k\w+)\[\]", line)
        if m:
            cur = tables.setdefault(m.group(1), {})
            continue
        m = re.match(r"\s*\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", line)
        if m and cur is not None:
            cur[chr(int(m.group(1), 16))] = chr(int(m.group(2), 16))
    return tables["kS2T"], tables["kT2S"]


def load_phrases(path):
    out = {}
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or "\t" not in line:
            continue
        key, values = line.rstrip("\r\n").split("\t")
        value = values.split(" ")[0]
        if len(key) >= 2 and len(value) == len(key):
            out.setdefault(key, value)
    return out


def convert(text, phrases, chars, maxlen):
    out, i = [], 0
    while i < len(text):
        for n in range(min(maxlen, len(text) - i), 1, -1):
            v = phrases.get(text[i:i + n])
            if v is not None:
                out.append(v)
                i += n
                break
        else:
            out.append(chars.get(text[i], text[i]))
            i += 1
    return "".join(out)


def prune(full, chars):
    kept = {k: v for k, v in full.items() if "".join(chars.get(c, c) for c in k) != v}
    while True:
        prefixes = set()
        for k in kept:
            for n in range(1, len(k) + 1):
                prefixes.add(k[:n])
        added = 0
        for k, v in full.items():
            if k in kept:
                continue
            conflict = any(k[:n] in kept for n in range(2, len(k)))
            for j in range(1, len(k)):
                if conflict:
                    break
                rest = k[j:]
                conflict = rest in prefixes or any(rest[:n] in kept for n in range(2, len(rest)))
            if conflict:
                kept[k] = v
                added += 1
        if not added:
            break
    maxlen = max(map(len, full))
    keys = list(full)
    tests = keys + [keys[i] + keys[i + 1] for i in range(len(keys) - 1)]
    assert all(convert(t, kept, chars, maxlen) == convert(t, full, chars, maxlen) for t in tests)
    return dict(sorted(kept.items()))


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--opencc", required=True)
    ap.add_argument("--inc")
    ap.add_argument("--lexi")
    a = ap.parse_args()
    s2t_chars, t2s_chars = load_chars()
    s2t = prune(load_phrases(os.path.join(a.opencc, "STPhrases.txt")), s2t_chars)
    t2s = prune(load_phrases(os.path.join(a.opencc, "TSPhrases.txt")), t2s_chars)
    print("s2t phrases: %d, t2s phrases: %d" % (len(s2t), len(t2s)))
    if a.inc:
        lines = [
            "// Generated by scripts/gen_zh_phrases.py from OpenCC STPhrases.txt / TSPhrases.txt (Apache-2.0).",
            "// Phrases (2+ characters, same length as their conversion) that character-level conversion gets wrong.",
            "struct ZhPhrase { const char* from; const char* to; };",
            "",
        ]
        for name, table in (("kS2TPhrases", s2t), ("kT2SPhrases", t2s)):
            lines.append("static const ZhPhrase %s[] = {" % name)
            lines += ["    {%s, %s}," % (c_str(k), c_str(v)) for k, v in table.items()]
            lines += ["};", "static const size_t %sCount = %d;" % (name, len(table)), ""]
        with open(a.inc, "w", encoding="utf-8", newline="\r\n") as f:
            f.write("\n".join(lines))
    if a.lexi:
        head = "# OpenCC phrase table (Apache-2.0), via DocuCraft scripts/gen_zh_phrases.py: one pair per line, from<TAB>to"
        for name, table in (("s2t_phrases.txt", s2t), ("t2s_phrases.txt", t2s)):
            with open(os.path.join(a.lexi, name), "w", encoding="utf-8", newline="\r\n") as f:
                f.write(head + "\n" + "".join("%s\t%s\n" % kv for kv in table.items()))


if __name__ == "__main__":
    main()
